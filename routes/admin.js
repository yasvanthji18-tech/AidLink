// PATCH /api/admin/settings/toggle-test-mode
router.patch('/settings/toggle-test-mode', protect, authorize('admin'), async (req, res) => {
  try {
    let settings = await SystemSetting.findOne();
    if (!settings) {
      settings = new SystemSetting({ testMode: false, testCenterIds: [] });
    }

    settings.testMode = !settings.testMode;

    if (settings.testMode) {
      // Pick 3 centers: First 3 verified centers
      const centers = await ServiceCenter.find({ isActive: true, verified: true }).limit(3);
      settings.testCenterIds = centers.map(c => c._id);
    }

    await settings.save();
    const populated = await settings.populate('testCenterIds');
    
    console.log(`[ADMIN] Test Mode Toggled: ${settings.testMode}`);
    res.json({ success: true, data: populated });
  } catch (err) {
    console.error(`[ADMIN] Toggle Error: ${err.message}`);
    res.status(400).json({ success: false, message: err.message });
  }
});

// GET /api/admin/system-report - Full system health report
router.get('/system-report', protect, authorize('admin'), async (req, res) => {
  try {
    const [
      totalCenters, verifiedCenters, totalVolunteers, totalDonations
    ] = await Promise.all([
      ServiceCenter.countDocuments(),
      ServiceCenter.countDocuments({ verified: true }),
      User.countDocuments({ role: 'volunteer' }),
      Donation.countDocuments(),
    ]);

    const donationStatusCounts = await Donation.aggregate([
      { $group: { _id: '$status', count: { $sum: 1 } } }
    ]);
    const statusMap = donationStatusCounts.reduce((a, d) => ({ ...a, [d._id]: d.count }), {});

    const completedDonations = (statusMap['received_by_center'] || 0) + (statusMap['received'] || 0);
    const cancelledDonations = statusMap['cancelled'] || 0;
    const pendingDonations = totalDonations - completedDonations - cancelledDonations;

    // Failed flows: stuck in rejected_by_all
    const failedFlows = await Donation.find({ centerStatus: 'rejected_by_all' })
      .select('title type status location.city createdAt')
      .sort({ createdAt: -1 })
      .limit(20);

    // Unassigned donations (no center)
    const unassigned = await Donation.countDocuments({ assignedCenterId: null });

    // Donations waiting for volunteer > 30 minutes
    const thirtyMinsAgo = new Date(Date.now() - 30 * 60 * 1000);
    const stalePending = await Donation.countDocuments({
      status: 'waiting_for_volunteer',
      waitingForVolunteerSince: { $lte: thirtyMinsAgo },
      fallbackTriggered: false,
    });

    // Centers with no needs listed
    const centersWithNoNeeds = await ServiceCenter.countDocuments({ needs: { $size: 0 } });

    // Logical inconsistency: donations "accepted" by center but no volunteer, past 1 hr
    const oneHourAgo = new Date(Date.now() - 60 * 60 * 1000);
    const missingVolunteer = await Donation.countDocuments({
      status: 'waiting_for_volunteer',
      centerStatus: 'accepted',
      waitingForVolunteerSince: { $lte: oneHourAgo },
    });

    console.log(`[ADMIN] System Report generated by ${req.user.name}`);
    res.json({
      success: true,
      data: {
        serviceCenters: { total: totalCenters, verified: verifiedCenters, unverified: totalCenters - verifiedCenters },
        volunteers: { total: totalVolunteers },
        donations: {
          total: totalDonations,
          completed: completedDonations,
          pending: pendingDonations,
          cancelled: cancelledDonations,
          unassigned,
        },
        issues: {
          failedFlows: failedFlows.length,
          failedFlowDetails: failedFlows,
          stalePendingVolunteer: stalePending,
          missingVolunteerLongWait: missingVolunteer,
          centersWithNoNeeds,
        },
        generatedAt: new Date(),
      }
    });
  } catch (err) {
    console.error(`[ADMIN] System Report Error: ${err.message}`);
    res.status(500).json({ success: false, message: err.message });
  }
});

