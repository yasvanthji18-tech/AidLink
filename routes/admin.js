// PATCH /api/admin/users/:id/toggle - Toggle user active status
router.patch('/users/:id/toggle', protect, authorize('admin'), async (req, res) => {
  try {
    const user = await User.findById(req.params.id);
    if (!user) return res.status(404).json({ success: false, message: 'User not found' });
    user.isActive = !user.isActive;
    await user.save();
    console.log(`[ADMIN] User Toggle: ${user.email} -> ${user.isActive}`);
    res.json({ success: true, data: user });
  } catch (err) {
    console.error(`[ADMIN] User Toggle Error: ${err.message}`);
    res.status(400).json({ success: false, message: err.message });
  }
});

// PATCH /api/admin/verify-center - Verify a service center
router.patch('/verify-center', protect, authorize('admin'), async (req, res) => {
  try {
    const { centerId, verified } = req.body;
    const center = await ServiceCenter.findByIdAndUpdate(
      centerId,
      {
        verified,
        verifiedAt: verified ? new Date() : null,
        verificationStatus: verified ? 'verified' : 'unverified',
      },
      { new: true }
    );
    if (!center) return res.status(404).json({ success: false, message: 'Service center not found' });
    console.log(`[ADMIN] Center Verify: ${center.name} -> ${verified}`);
    res.json({ success: true, data: center });
  } catch (err) {
    console.error(`[ADMIN] Center Verify Error: ${err.message}`);
    res.status(400).json({ success: false, message: err.message });
  }
});

// PATCH /api/admin/users/:id/verify - Set volunteer/donor verification status
router.patch('/users/:id/verify', protect, authorize('admin'), async (req, res) => {
  try {
    const { verificationStatus } = req.body;
    if (!['unverified', 'verified', 'trusted'].includes(verificationStatus)) {
      return res.status(400).json({ success: false, message: 'Invalid verification status' });
    }
    const user = await User.findByIdAndUpdate(
      req.params.id,
      { verificationStatus },
      { new: true }
    ).select('-passwordHash');
    if (!user) return res.status(404).json({ success: false, message: 'User not found' });
    console.log(`[ADMIN] User Verify: ${user.email} -> ${verificationStatus}`);
    res.json({ success: true, data: user });
  } catch (err) {
    console.error(`[ADMIN] User Verify Error: ${err.message}`);
    res.status(400).json({ success: false, message: err.message });
  }
});

