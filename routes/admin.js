const express = require('express');
const router = express.Router();
const User = require('../models/User');
const Donation = require('../models/Donation');
const ServiceCenter = require('../models/ServiceCenter');
const Task = require('../models/Task');
const Funding = require('../models/Funding');
const SystemSetting = require('../models/SystemSetting');
const { protect, authorize } = require('../middleware/auth');

// GET /api/admin/dashboard - Platform statistics
router.get('/dashboard', protect, authorize('admin'), async (req, res) => {
  try {
    const [totalUsers, totalDonations, totalCenters, verifiedCenters, totalTasks, totalFunding] =
      await Promise.all([
        User.countDocuments(),
        Donation.countDocuments(),
        ServiceCenter.countDocuments(),
        ServiceCenter.countDocuments({ verified: true }),
        Task.countDocuments(),
        Funding.aggregate([{ $group: { _id: null, total: { $sum: '$amount' } } }]),
      ]);

    const donationsByType = await Donation.aggregate([
      { $group: { _id: '$type', count: { $sum: 1 } } },
    ]);
    const donationsByStatus = await Donation.aggregate([
      { $group: { _id: '$status', count: { $sum: 1 } } },
    ]);
    const usersByRole = await User.aggregate([
      { $group: { _id: '$role', count: { $sum: 1 } } },
    ]);

    let systemSettings = await SystemSetting.findOne().populate('testCenterIds');
    if (!systemSettings) {
      systemSettings = await SystemSetting.create({ testMode: false, testCenterIds: [] });
    }

    const testCenters = systemSettings.testCenterIds || [];
    
    // Aggregation for volunteer visibility
    const volunteersWithTaskCounts = await User.aggregate([
      { $match: { role: 'volunteer' } },
      {
        $lookup: {
          from: 'tasks',
          localField: '_id',
          foreignField: 'volunteerId',
          as: 'tasks',
        },
      },
      {
        $project: {
          name: 1,
          location: 1,
          volunteerPoints: 1,
          taskCount: { $size: '$tasks' },
        },
      },
      { $sort: { volunteerPoints: -1 } },
    ]);

    console.log(`[ADMIN] Dashboard Stats generated by ${req.user.name}`);
    res.json({ success: true, data: {
      totalUsers,
      totalDonations,
      totalCenters,
      verifiedCenters,
      totalTasks,
      totalFundingAmount: totalFunding[0]?.total || 0,
      donationsByType,
      donationsByStatus,
      usersByRole,
      testMode: systemSettings.testMode,
      testCenters,
      volunteers: volunteersWithTaskCounts
    }});
  } catch (err) {
    console.error(`[ADMIN] Dashboard Error: ${err.message}`);
    res.status(500).json({ success: false, message: err.message });
  }
});

